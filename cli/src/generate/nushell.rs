use super::quote::{nu_dquote, nu_literal, ps_squote_inner};
use crate::definitions::{Definitions, LauncherType, Platform};
use std::fmt::Write;
use std::path::Path;

/// `_dotfiles_dir` is unused: script wrappers resolve the root at run time through
/// `$env.DOT` (nushell/env.nu), so the output does not depend on where it was generated.
pub fn generate(defs: &Definitions, _dotfiles_dir: &Path) -> String {
    let mut out = String::new();

    writeln!(out, "# Auto-generated by dotcli — DO NOT EDIT").unwrap();
    writeln!(out).unwrap();

    // _dotcli_apply helper
    writeln!(out, "{}", APPLY_HELPER).unwrap();

    // _dotcli_launch helper (detached external process via `dotcli detach`)
    writeln!(out, "{}", LAUNCH_HELPER).unwrap();

    // Aliases
    if !defs.alias.is_empty() {
        writeln!(out, "# --- Aliases ---").unwrap();
        for a in &defs.alias {
            if a.args.is_empty() {
                writeln!(out, "alias {name} = {cmd}", name = a.name, cmd = a.command,).unwrap();
            } else {
                // nushell alias can include args
                writeln!(
                    out,
                    "alias {name} = {cmd} {args}",
                    name = a.name,
                    cmd = a.command,
                    args = a.args.join(" "),
                )
                .unwrap();
            }
        }
        writeln!(out).unwrap();
    }

    // Script wrappers (.ps1 via pwsh)
    if !defs.script.is_empty() {
        writeln!(out, "# --- Script wrappers ---").unwrap();
        for s in &defs.script {
            let segments = s
                .path
                .replace('\\', "/")
                .split('/')
                .map(nu_literal)
                .collect::<Vec<_>>()
                .join(" ");
            // -NoProfile, as in bash.rs: nushell is interactive, so a plain `pwsh -File`
            // would run profile.ps1's interactive part (mise, zoxide, starship, ...) on
            // every call. Each [[script]] must dot-source pwsh/aliases.ps1 itself when it
            // uses those aliases; under -NoProfile `sc` resolves to sc.exe.
            writeln!(
                out,
                "def {name} [...args: string] {{ pwsh -NoProfile -File ([$env.DOT {segments}] | path join) ...$args }}",
                name = s.name,
                segments = segments,
            )
            .unwrap();
        }
        writeln!(out).unwrap();
    }

    // Launchers (Windows — nushell `start` opens URIs and exes)
    let win_launchers: Vec<_> = defs
        .launcher
        .iter()
        .filter(|l| l.platform.as_ref() != Some(&Platform::Macos) && l.nushell)
        .collect();
    if !win_launchers.is_empty() {
        writeln!(out, "# --- Launchers ---").unwrap();
        for l in &win_launchers {
            match l.launcher_type {
                LauncherType::Uri => {
                    writeln!(
                        out,
                        "def {name} [] {{ start {uri} }}",
                        name = l.name,
                        uri = l.uri.as_ref().unwrap(),
                    )
                    .unwrap();
                }
                LauncherType::Exe => {
                    let raw_path = l.path.as_ref().unwrap();
                    let path_expr = if raw_path.contains("{PROGRAM_FILES}") {
                        let rest = raw_path
                            .replace("{PROGRAM_FILES}\\", "")
                            .replace("{PROGRAM_FILES}", "");
                        let segments = rest
                            .split('\\')
                            .filter(|s| !s.is_empty())
                            .map(nu_dquote)
                            .collect::<Vec<_>>()
                            .join(" ");
                        format!("([$env.ProgramFiles {segments}] | path join)")
                    } else if raw_path.contains("{USERPROFILE}") {
                        let rest = raw_path
                            .replace("{USERPROFILE}\\", "")
                            .replace("{USERPROFILE}", "");
                        let segments = rest
                            .split('\\')
                            .filter(|s| !s.is_empty())
                            .map(nu_dquote)
                            .collect::<Vec<_>>()
                            .join(" ");
                        format!("([$env.USERPROFILE {segments}] | path join)")
                    } else if raw_path.contains('\\') {
                        // Literal without escape processing. Splitting on `\` and joining
                        // with `path join` would turn `C:\x` into the drive-relative `C:x`.
                        nu_literal(raw_path)
                    } else {
                        // Bare exe — pass as quoted literal to _dotcli_launch (resolved via PATH)
                        nu_dquote(raw_path)
                    };
                    let args_str = l
                        .args
                        .iter()
                        .map(|a| nu_dquote(a))
                        .collect::<Vec<_>>()
                        .join(" ");
                    if args_str.is_empty() {
                        writeln!(
                            out,
                            "def {name} [] {{ _dotcli_launch {path} }}",
                            name = l.name,
                            path = path_expr,
                        )
                        .unwrap();
                    } else {
                        writeln!(
                            out,
                            "def {name} [] {{ _dotcli_launch {path} {args} }}",
                            name = l.name,
                            path = path_expr,
                            args = args_str,
                        )
                        .unwrap();
                    }
                }
                LauncherType::StartApp => {
                    let app = l.app_name.as_ref().unwrap();
                    // Same inline command as bash.rs, so it needs no profile (Start-App).
                    let ps_cmd = format!(
                        "explorer \"shell:AppsFolder\\$((Get-StartApps '{}' | Select-Object -First 1).AppID)\"",
                        ps_squote_inner(app)
                    );
                    writeln!(
                        out,
                        "def {name} [] {{ ^pwsh -NoProfile -Command {cmd} }}",
                        name = l.name,
                        cmd = nu_literal(&ps_cmd),
                    )
                    .unwrap();
                }
            }
        }
        writeln!(out).unwrap();
    }

    // Complex commands (dotcli subcommands)
    let cmds: Vec<_> = defs.command.iter().filter(|c| c.enabled).collect();
    if !cmds.is_empty() {
        writeln!(out, "# --- Commands (via dotcli) ---").unwrap();
        for c in &cmds {
            if c.modifies_shell {
                writeln!(
                    out,
                    "def --env {name} [...args: string] {{ dotcli {sub} ...$args | _dotcli_apply }}",
                    name = c.name,
                    sub = c.subcommand,
                )
                .unwrap();
            } else {
                writeln!(
                    out,
                    "def {name} [...args: string] {{ dotcli {sub} ...$args }}",
                    name = c.name,
                    sub = c.subcommand,
                )
                .unwrap();
            }
        }
    }

    out
}

#[cfg(test)]
mod tests {
    use super::generate;
    use crate::definitions::{Definitions, Platform};
    use crate::generate::powershell;
    use std::path::Path;
    use std::process::Command;

    fn dotfiles_path() -> &'static Path {
        Path::new("C:/Main/dotfiles")
    }

    /// cli/definitions.toml of this checkout, independent of the test cwd.
    fn load_definitions() -> Definitions {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("definitions.toml");
        Definitions::load(Some(&path)).unwrap()
    }

    fn nu_available() -> bool {
        Command::new("nu")
            .arg("--version")
            .stdout(std::process::Stdio::null())
            .stderr(std::process::Stdio::null())
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    }

    #[test]
    fn nushell_covers_definitions_present_in_powershell() {
        let defs = load_definitions();
        let ps = powershell::generate(&defs, dotfiles_path());
        let nu = generate(&defs, dotfiles_path());

        for a in &defs.alias {
            let marker = format!("function {} {{", a.name);
            assert!(
                ps.contains(&marker),
                "alias {} expected in PowerShell output",
                a.name
            );
            let marker = format!("alias {} =", a.name);
            assert!(
                nu.contains(&marker),
                "alias {} missing from nushell output",
                a.name
            );
        }

        for s in &defs.script {
            let marker = format!("function {} {{", s.name);
            assert!(
                ps.contains(&marker),
                "script {} expected in PowerShell output",
                s.name
            );
            let marker = format!("def {} [", s.name);
            assert!(
                nu.contains(&marker),
                "script {} missing from nushell output",
                s.name
            );
        }

        for l in &defs.launcher {
            if l.platform.as_ref() == Some(&Platform::Macos) {
                continue;
            }
            let ps_marker = format!("function {} {{", l.name);
            assert!(
                ps.contains(&ps_marker),
                "launcher {} expected in PowerShell output",
                l.name
            );
            let nu_marker = format!("def {} [", l.name);
            if l.nushell {
                assert!(
                    nu.contains(&nu_marker),
                    "launcher {} missing from nushell output",
                    l.name
                );
            } else {
                assert!(
                    !nu.contains(&nu_marker),
                    "launcher {} should be excluded from nushell output",
                    l.name
                );
            }
        }

        for c in &defs.command {
            if !c.enabled {
                let marker = format!("function {} {{", c.name);
                assert!(
                    !ps.contains(&marker),
                    "disabled command {} must not appear in PowerShell output",
                    c.name
                );
                assert!(
                    !nu.contains(&format!("def {} [", c.name))
                        && !nu.contains(&format!("def --env {} [", c.name)),
                    "disabled command {} must not appear in nushell output",
                    c.name
                );
                continue;
            }
            let marker = format!("function {} {{", c.name);
            assert!(
                ps.contains(&marker),
                "command {} expected in PowerShell output",
                c.name
            );
            let marker = if c.modifies_shell {
                format!("def --env {} [", c.name)
            } else {
                format!("def {} [", c.name)
            };
            assert!(
                nu.contains(&marker),
                "command {} missing from nushell output",
                c.name
            );
        }
    }

    fn defs_from(toml_src: &str) -> Definitions {
        toml::from_str(toml_src).expect("test definitions must parse")
    }

    /// definitions.toml itself may hold no disabled command, so the `enabled` filter of
    /// all three generators is checked on a synthetic pair of commands.
    #[test]
    fn disabled_commands_are_left_out_of_every_generator() {
        let defs = defs_from(
            r#"
[[command]]
name = "on"
subcommand = "on-sub"
modifies_shell = true

[[command]]
name = "off"
subcommand = "off-sub"
modifies_shell = true
enabled = false
"#,
        );
        let ps = powershell::generate(&defs, dotfiles_path());
        let nu = generate(&defs, dotfiles_path());
        let sh = crate::generate::bash::generate(&defs, dotfiles_path());
        for (shell, out) in [("PowerShell", &ps), ("nushell", &nu), ("bash", &sh)] {
            assert!(out.contains("on-sub"), "enabled command missing from {shell} output");
            assert!(!out.contains("off-sub"), "disabled command present in {shell} output");
        }
    }

    #[test]
    fn absolute_exe_launcher_is_a_literal_with_drive_root() {
        let defs = defs_from(
            r#"
[[launcher]]
name = "abs"
type = "exe"
path = 'C:\Main\x y\a.exe'

[[launcher]]
name = "quoted"
type = "exe"
path = "C:\\it's\\a.exe"
"#,
        );
        let nu = generate(&defs, dotfiles_path());
        assert!(
            nu.contains(r"def abs [] { _dotcli_launch 'C:\Main\x y\a.exe' }"),
            "{nu}"
        );
        assert!(
            nu.contains(r"def quoted [] { _dotcli_launch r#'C:\it's\a.exe'# }"),
            "{nu}"
        );
    }

    #[test]
    fn script_wrapper_uses_noprofile_and_env_dot() {
        let defs = defs_from(
            r#"
[[script]]
name = "gnew"
path = 'bin\git-new.ps1'
"#,
        );
        let nu = generate(&defs, dotfiles_path());
        assert!(
            nu.contains(
                "def gnew [...args: string] { pwsh -NoProfile -File ([$env.DOT 'bin' 'git-new.ps1'] | path join) ...$args }"
            ),
            "{nu}"
        );
        assert!(!nu.contains("C:/Main/dotfiles"), "generation root leaked: {nu}");
    }

    #[test]
    fn start_app_launcher_runs_inline_without_profile() {
        let defs = defs_from(
            r#"
[[launcher]]
name = "ncal"
type = "start_app"
app_name = "Notion Calendar"
"#,
        );
        let nu = generate(&defs, dotfiles_path());
        assert!(
            nu.contains(
                r#"def ncal [] { ^pwsh -NoProfile -Command r#'explorer "shell:AppsFolder\$((Get-StartApps 'Notion Calendar' | Select-Object -First 1).AppID)"'# }"#
            ),
            "{nu}"
        );
        assert!(!nu.contains("Start-App"), "{nu}");
    }

    #[test]
    fn nu_literal_round_trips_through_nu() {
        if !nu_available() {
            return;
        }
        for s in [
            r"C:\Main\x y\a.exe",
            r"C:\it's\a.exe",
            r"a'#b",
            r"a'#'##c",
            r#"say "hi" \n $x"#,
        ] {
            let lit = super::nu_literal(s);
            let out = Command::new("nu")
                .args(["-n", "-c", &format!("print -n {lit}")])
                .output()
                .expect("failed to spawn nu");
            assert!(out.status.success(), "nu failed on {lit}: {:?}", out);
            assert_eq!(String::from_utf8_lossy(&out.stdout), s, "literal {lit}");
        }
    }

    #[test]
    fn nushell_generated_passes_ide_check() {
        if !nu_available() {
            return;
        }
        let defs = load_definitions();
        let nu_src = generate(&defs, dotfiles_path());
        let path = std::env::temp_dir().join(format!(
            "dotcli-ide-check-{}.nu",
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        std::fs::write(&path, &nu_src).unwrap();
        let status = Command::new("nu")
            .args(["--ide-check", "0", path.to_str().unwrap()])
            .status()
            .expect("failed to spawn nu");
        let _ = std::fs::remove_file(&path);
        assert!(
            status.success(),
            "nu --ide-check failed with status {:?}",
            status.code()
        );
    }
}

// `dotcli detach` (commands/detach.rs) starts the program detached and passes the
// arguments as given. `cmd /c start` made cmd.exe re-parse them (& | < > ^ ( ) %NAME%),
// `job spawn` gets its processes killed when nushell exits, and pwsh's Start-Process
// costs ~300 ms per launch to start pwsh.
const LAUNCH_HELPER: &str = r#"def _dotcli_launch [program: string, ...args: string] {
    # dotcli detach: 引数を cmd.exe に解釈させず、nu から切り離して起動する (nu を終えても残る)
    ^dotcli detach $program ...$args
}
"#;

// A failing dotcli (non-zero exit, `exit_code` in the JSON) still reaches this helper
// and its messages print, but `$env.LAST_EXIT_CODE` stays 0: nushell drops the status of
// an external command whose output is piped on, and the REPL resets LAST_EXIT_CODE after
// a custom command, so setting it here does not stick.
// TODO: propagate `exit_code` (e.g. end with an external that exits with it) if scripts
// ever need to test it.
const APPLY_HELPER: &str = r#"def --env _dotcli_apply [] {
    let action = ($in | from json)
    if ($action | get -o unset_env | is-not-empty) {
        for k in $action.unset_env { hide-env -i $k }
    }
    if ($action | get -o set_env | is-not-empty) {
        load-env $action.set_env
    }
    if ($action | get -o cd | is-not-empty) { cd $action.cd }
    if ($action | get -o messages | is-not-empty) {
        $action.messages | each { |m|
            let color = match $m.level { "warn" => "yellow", "error" => "red", _ => "green" }
            print $"(ansi $color)($m.text)(ansi reset)"
        } | ignore
    }
    if ($action | get -o exec | is-not-empty) {
        if $action.exec.program == "claude" {
            # Tag pane for WezTerm Alt+Z redraw detection (app=claude).
            # Emit on stderr to bypass pipe consumption by surrounding pipeline.
            print -ne $"(char -u "1b")]1337;SetUserVar=app=Y2xhdWRl(char -u "07")"
        }
        ^($action.exec.program) ...($action.exec.args)
    }
}
"#;
