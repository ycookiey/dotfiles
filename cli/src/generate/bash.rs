use crate::definitions::{Definitions, LauncherType, Platform};
use std::fmt::Write;
use std::path::Path;

pub fn generate(defs: &Definitions, dotfiles_dir: &Path) -> String {
    let mut out = String::new();
    let dotfiles = dotfiles_dir.to_string_lossy().replace('\\', "/");

    writeln!(out, "# Auto-generated by dotcli — DO NOT EDIT").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "{}", APPLY_HELPER).unwrap();

    if !defs.alias.is_empty() {
        writeln!(out, "# --- Aliases ---").unwrap();
        for a in &defs.alias {
            let args_str = if a.args.is_empty() {
                String::new()
            } else {
                let parts: Vec<String> = a.args.iter().map(|x| bash_squote(x)).collect();
                format!(" {}", parts.join(" "))
            };
            writeln!(
                out,
                "{name}() {{ {cmd}{args} \"$@\"; }}",
                name = a.name,
                cmd = a.command,
                args = args_str,
            )
            .unwrap();
        }
        writeln!(out).unwrap();
    }

    if !defs.script.is_empty() {
        writeln!(out, "# --- Script wrappers ---").unwrap();
        for s in &defs.script {
            let path = format!("{}/{}", dotfiles, s.path.replace('\\', "/"));
            writeln!(
                out,
                "{name}() {{ pwsh -NoProfile -File {path} \"$@\"; }}",
                name = s.name,
                path = bash_squote(&path),
            )
            .unwrap();
        }
        writeln!(out).unwrap();
    }

    let win_launchers: Vec<_> = defs
        .launcher
        .iter()
        .filter(|l| l.platform.as_ref() != Some(&Platform::Macos))
        .collect();
    if !win_launchers.is_empty() {
        writeln!(out, "# --- Launchers ---").unwrap();
        for l in &win_launchers {
            match l.launcher_type {
                LauncherType::Uri => {
                    let uri = l.uri.as_ref().unwrap();
                    writeln!(
                        out,
                        "{name}() {{ explorer.exe {uri}; }}",
                        name = l.name,
                        uri = bash_squote(uri),
                    )
                    .unwrap();
                }
                LauncherType::StartApp => {
                    let app = l.app_name.as_ref().unwrap();
                    let ps_cmd = format!(
                        "explorer \"shell:AppsFolder\\$((Get-StartApps '{}' | Select-Object -First 1).AppID)\"",
                        ps_squote_inner(app)
                    );
                    writeln!(
                        out,
                        "{name}() {{ pwsh -NoProfile -Command {cmd}; }}",
                        name = l.name,
                        cmd = bash_squote(&ps_cmd),
                    )
                    .unwrap();
                }
                LauncherType::Exe => {
                    let raw_path = l.path.as_ref().unwrap();
                    let has_env_var = raw_path.contains("{PROGRAM_FILES}")
                        || raw_path.contains("{USERPROFILE}");
                    let path_part = if has_env_var {
                        // PS double-quoted to expand $env: variables
                        let p = raw_path
                            .replace("{PROGRAM_FILES}", "$env:ProgramFiles")
                            .replace("{USERPROFILE}", "$env:USERPROFILE");
                        format!("\"{}\"", p.replace('"', "`\""))
                    } else {
                        format!("'{}'", ps_squote_inner(raw_path))
                    };
                    let arglist = if l.args.is_empty() {
                        String::new()
                    } else {
                        let pwsh_args: Vec<String> = l
                            .args
                            .iter()
                            .map(|a| format!("'{}'", ps_squote_inner(a)))
                            .collect();
                        format!(" -ArgumentList {}", pwsh_args.join(","))
                    };
                    let ps_cmd = format!("Start-Process -FilePath {}{}", path_part, arglist);
                    writeln!(
                        out,
                        "{name}() {{ pwsh -NoProfile -Command {cmd}; }}",
                        name = l.name,
                        cmd = bash_squote(&ps_cmd),
                    )
                    .unwrap();
                }
            }
        }
        writeln!(out).unwrap();
    }

    let cmds: Vec<_> = defs.command.iter().filter(|c| c.enabled).collect();
    if !cmds.is_empty() {
        writeln!(out, "# --- Commands (via dotcli) ---").unwrap();
        for c in &cmds {
            if c.modifies_shell {
                writeln!(
                    out,
                    "{name}() {{ local _dotcli_out; _dotcli_out=$(dotcli {sub} \"$@\"); _dotcli_apply \"$_dotcli_out\" \"$?\"; }}",
                    name = c.name,
                    sub = c.subcommand,
                )
                .unwrap();
            } else {
                writeln!(
                    out,
                    "{name}() {{ dotcli {sub} \"$@\"; }}",
                    name = c.name,
                    sub = c.subcommand,
                )
                .unwrap();
            }
        }
    }

    out
}

fn bash_squote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

fn ps_squote_inner(s: &str) -> String {
    s.replace('\'', "''")
}

/// Shell side of `protocol::ShellAction`. One jq call turns the JSON into shell code that
/// `eval` runs, so every value from the JSON must reach that code through `q` (`@sh`).
/// jq's output must contain no raw newline: Windows jq writes LF as CRLF on stdout, which
/// would leave `\r` in values (`-b` avoids that only on jq >= 1.7).
const APPLY_HELPER: &str = r##"_dotcli_msg() {
    case "$1" in
        warn) printf '\033[33m%s\033[0m\n' "$2" ;;
        error) printf '\033[31m%s\033[0m\n' "$2" ;;
        *) printf '\033[32m%s\033[0m\n' "$2" ;;
    esac
}

# Bash's exec skips PATHEXT and command_not_found_handle, so resolve .cmd/.bat first.
# TODO: exec replaces this shell (the pane closes when the program exits), while pwsh and
# nushell run the program as a child. Drop `exec` here to match them if that is preferred.
_dotcli_exec() {
    local _dotcli_prog
    _dotcli_prog=$(type -P -- "$1" || type -P -- "$1.cmd" || type -P -- "$1.bat") || _dotcli_prog=$1
    # Tag pane for WezTerm Alt+Z redraw detection (app=claude).
    [ "$1" = claude ] && printf '\033]1337;SetUserVar=app=Y2xhdWRl\007'
    shift
    exec "$_dotcli_prog" "$@"
}

# Usage: _dotcli_apply JSON [RC]
# Applies the JSON a dotcli subcommand printed. Returns the action's exit_code, the exec'd
# program's status, or else RC (the dotcli exit status).
_dotcli_apply() {
    [ -z "$1" ] && return "${2:-0}"
    if ! command -v jq >/dev/null 2>&1; then
        printf 'dotcli: jq is required for shell-modifying commands\n' >&2
        return 1
    fi
    local _dotcli_code
    _dotcli_code=$(jq -j --arg q "'" '
        def q: @sh | gsub("\n"; "\($q)$\($q)\\n\($q)\($q)");
        def name: test("^[A-Za-z_][A-Za-z0-9_]*$");
        def bad_name: "_dotcli_msg error \("dotcli: invalid variable name: \(.)" | q)";
        [
            (.unset_env[]? | if name then "unset -v -- \(q)" else bad_name end),
            (.set_env // {} | to_entries[]
                | if .key | name then "export -- \("\(.key)=\(.value)" | q)" else .key | bad_name end),
            (.cd // empty | "cd -- \(q)"),
            (.messages[]? | "_dotcli_msg \(.level | q) \(.text | q)"),
            (.exec // empty | "_dotcli_exec \([.program] + (.args // []) | map(q) | join(" ")); return"),
            (.exit_code // 0 | numbers | select(. != 0) | "return \(floor)"),
            "return \"${2:-0}\""
        ] | join("; ")' <<<"$1") || return 1
    eval "$_dotcli_code"
}
"##;
